// Command genworker writes the word lists and the scoring examples the Worker
// needs, from the same files the game embeds:
//
//	worker/src/gen/words.ts         answers, guesses and the name blocklist
//	worker/test/score-vectors.json  guesses scored by game.Score
//
// Run it from the repository root after any change to internal/words/data.
// CI runs it and fails if the output differs from what is committed, the same
// way it checks THIRD_PARTY_NOTICES.md.
package main

import (
	"fmt"
	"log"
	"math/rand/v2"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/nxck2005/surmise/internal/game"
)

// lengths are the word modes, the way internal/words orders them.
var lengths = []int{4, 5, 6}

func main() {
	log.SetFlags(0)

	if _, err := os.Stat("go.mod"); err != nil {
		log.Fatal("genworker: run from the repository root")
	}

	answers, guesses := readLists()
	offensive := readOffensive()

	writeWords(answers, guesses, offensive)
	writeVectors(answers, guesses)
}

// readLists reads the answer and guess lists in file order. The order is the
// one the daily draws from, so it must not be sorted here.
func readLists() (map[int][]string, map[int][]string) {
	answers := map[int][]string{}
	guesses := map[int][]string{}
	for _, n := range lengths {
		answers[n] = readWords(fmt.Sprintf("internal/words/data/answers%d.txt", n))
		guesses[n] = readWords(fmt.Sprintf("internal/words/data/guesses%d.txt", n))
	}
	return answers, guesses
}

func readWords(name string) []string {
	b, err := os.ReadFile(name)
	if err != nil {
		log.Fatalf("%s", err)
	}
	return strings.Fields(string(b))
}

// readOffensive merges blocked.txt and profanity.txt, the two lists a display
// name is held against, into one lowercase sorted list. Words carry no
// comments of their own: a line that is empty or starts with # is prose.
func readOffensive() []string {
	seen := map[string]struct{}{}
	for _, name := range []string{"internal/words/data/blocked.txt", "internal/words/data/profanity.txt"} {
		b, err := os.ReadFile(name)
		if err != nil {
			log.Fatalf("%s", err)
		}
		for _, line := range strings.Split(string(b), "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			for _, word := range strings.Fields(line) {
				seen[strings.ToLower(word)] = struct{}{}
			}
		}
	}
	out := make([]string, 0, len(seen))
	for word := range seen {
		out = append(out, word)
	}
	slices.Sort(out)
	return out
}

// writeWords writes worker/src/gen/words.ts, the Worker's generated copy of
// the lists, typed so the answer lists stay ordered where the guess and
// offensive lookups are sets.
func writeWords(answers, guesses map[int][]string, offensive []string) {
	var b strings.Builder
	b.WriteString("// Code generated by go run ./tools/genworker. DO NOT EDIT.\n")
	b.WriteString("// Source: internal/words/data. Regenerate after any change there.\n\n")
	b.WriteString("export const ANSWERS: Readonly<Record<number, readonly string[]>> = {\n")
	for _, n := range lengths {
		fmt.Fprintf(&b, "  %d: %q.split(\" \"),\n", n, strings.Join(answers[n], " "))
	}
	b.WriteString("};\n\n")
	b.WriteString("export const GUESSES: Readonly<Record<number, ReadonlySet<string>>> = {\n")
	for _, n := range lengths {
		fmt.Fprintf(&b, "  %d: new Set(%q.split(\" \")),\n", n, strings.Join(guesses[n], " "))
	}
	b.WriteString("};\n\n")
	b.WriteString("export const OFFENSIVE: ReadonlySet<string> = new Set(")
	fmt.Fprintf(&b, "%q.split(\" \"));\n", strings.Join(offensive, " "))

	write("worker/src/gen/words.ts", []byte(b.String()))
}

// writeVectors writes the score examples: the fixed pairs the Go tests call
// out by name, then 400 pairs per length from one seeded draw, so a change to
// the TS scorer or the data files shows up as a diff.
func writeVectors(answers, guesses map[int][]string) {
	type pair struct{ guess, answer string }

	fixed := []pair{
		{"allot", "lotto"}, {"speed", "abide"}, {"eerie", "there"},
		{"abbey", "babes"}, {"llama", "label"}, {"crane", "crane"},
		{"aaaaa", "abcde"}, {"noon", "onto"}, {"book", "kobo"},
		{"banana", "ananas"}, {"letter", "settle"},
	}
	var pairs = slices.Clone(fixed)
	for _, n := range lengths {
		r := rand.New(rand.NewPCG(uint64(n), 0x5eed))
		for range 400 {
			guess := guesses[n][r.IntN(len(guesses[n]))]
			answer := answers[n][r.IntN(len(answers[n]))]
			pairs = append(pairs, pair{guess, answer})
		}
	}

	var b strings.Builder
	b.WriteString("[\n")
	for i, p := range pairs {
		marks := make([]string, 0, len(p.guess))
		for _, m := range game.Score(p.guess, p.answer) {
			marks = append(marks, fmt.Sprint(int(m)))
		}
		comma := ","
		if i == len(pairs)-1 {
			comma = ""
		}
		fmt.Fprintf(&b, "{\"guess\":%q,\"answer\":%q,\"marks\":[%s]}%s\n",
			p.guess, p.answer, strings.Join(marks, ","), comma)
	}
	b.WriteString("]\n")

	write("worker/test/score-vectors.json", []byte(b.String()))
}

func write(name string, b []byte) {
	if err := os.MkdirAll(filepath.Dir(name), 0o755); err != nil {
		log.Fatalf("%s", err)
	}
	if err := os.WriteFile(name, b, 0o644); err != nil {
		log.Fatalf("%s", err)
	}
	log.Printf("wrote %s", name)
}
