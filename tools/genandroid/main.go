// Command genandroid writes the Android resources that come from the Go side:
//
//	android/app/src/main/res/values/brand.xml  the app name, from internal/brand
//
// The product's name lives only in internal/brand, so the app's label is
// generated rather than typed into the Android project. Run it from the
// repository root after any change to brand.Name. CI runs it and fails if the
// output differs from what is committed, the same way it checks genworker.
package main

import (
	"bytes"
	"encoding/xml"
	"log"
	"os"
	"path/filepath"

	"github.com/nxck2005/surmise/internal/brand"
)

const out = "android/app/src/main/res/values/brand.xml"

func main() {
	log.SetFlags(0)

	if _, err := os.Stat("go.mod"); err != nil {
		log.Fatal("genandroid: run from the repository root")
	}

	var b bytes.Buffer
	b.WriteString(`<?xml version="1.0" encoding="utf-8"?>` + "\n")
	b.WriteString("<!-- Code generated by go run ./tools/genandroid. DO NOT EDIT. -->\n")
	b.WriteString("<resources>\n")
	b.WriteString(`    <string name="app_name" translatable="false">`)
	if err := xml.EscapeText(&b, []byte(brand.Name)); err != nil {
		log.Fatal(err)
	}
	b.WriteString("</string>\n")
	b.WriteString("</resources>\n")

	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
